"""Run every experiment: python -m ruin_kelly [--quick]. Writes results/ in the current folder."""

from __future__ import annotations

import argparse
import platform
from importlib.metadata import version
from pathlib import Path

from . import experiments as ex
from . import plots

RESULTS = Path("results")


def md_table(df, formats: dict[str, str]) -> str:
    cols = list(formats)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        cells = ["–" if isinstance(row[c], float) and row[c] != row[c] else format(row[c], formats[c])
                 for c in cols]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(prog="ruin_kelly", description=__doc__)
    parser.add_argument("--quick", action="store_true", help="fewer simulated accounts (for testing)")
    args = parser.parse_args(argv)
    n = 20_000 if args.quick else 200_000
    RESULTS.mkdir(exist_ok=True)

    tables = {
        "validation": ex.validation(n),
        "challenge_by_risk": ex.challenge_by_risk(ex.RECORD_P, ex.RECORD_PAYOFF, ex.CHALLENGE, n),
        "challenge_by_risk_guarded": ex.challenge_by_risk(
            ex.RECORD_P, ex.RECORD_PAYOFF,
            ex.Rules(target=0.10, max_loss=0.10, daily_loss=0.05, trades_per_day=3,
                     stop_before_daily_breach=True), n),
        "pass_vs_win_rate": ex.pass_vs_win_rate(ex.RECORD_PAYOFF, 0.01, ex.CHALLENGE),
        "heatmap_payoff": ex.heatmap(ex.CHALLENGE, "payoff"),
        "heatmap_risk": ex.heatmap(ex.CHALLENGE, "risk"),
        "kelly_curves": ex.kelly_curves(),
        "kelly_drawdowns": ex.kelly_drawdowns(ex.RECORD_P, ex.RECORD_PAYOFF),
        "kelly_estimation_error": ex.estimation_error(),
    }
    for name, table in tables.items():
        table.to_csv(RESULTS / f"{name}.csv", index=False, float_format="%.6g")

    plots.pass_vs_win_rate(tables["pass_vs_win_rate"], RESULTS)
    plots.heatmap(tables["heatmap_payoff"], "payoff", RESULTS)
    plots.heatmap(tables["heatmap_risk"], "risk", RESULTS)
    plots.kelly_growth(RESULTS)
    plots.estimation_error(tables["kelly_estimation_error"], RESULTS)

    pct, num = ".1%", ".3f"
    challenge_cols = {"risk": ".2%", "pass": pct, "fail_overall": pct, "fail_daily": pct,
                      "expected_days": ".1f", "pass_within_60_days": pct, "simulated_pass": pct}
    report = "\n\n".join([
        "# Results",
        "Generated by `python -m ruin_kelly`. Everything here is mathematics and simulation "
        "under stated assumptions; no market data is used. The win rate and payoff come from "
        "a self-reported record of 12 trades and are highly uncertain.",
        f"Python {platform.python_version()}; " + ", ".join(
            f"{p} {version(p)}" for p in ("numpy", "scipy", "pandas", "matplotlib")) + ".",
        f"Monte Carlo runs use {n:,} simulated accounts per row.",
        "## 1. Validation: equal wins and losses (no daily limit, 10% target, 10% loss limit)",
        md_table(tables["validation"], {"risk": ".0%", "win_rate": ".2f", "formula_pass": ".6f",
                                         "chain_pass": ".6f", "simulated_pass": ".4f",
                                         "simulation_se": ".4f", "formula_trades": ".2f",
                                         "chain_trades": ".2f", "simulated_trades": ".2f"}),
        "## 2. Challenge (10% target, 10% overall, 5% daily, 3 trades a day), record edge "
        "(win rate 41.7%, payoff 2.28)",
        md_table(tables["challenge_by_risk"], challenge_cols),
        "### Same, but skipping any trade whose loss would breach the daily limit",
        md_table(tables["challenge_by_risk_guarded"], challenge_cols),
        "## 3. Pass probability across the plausible win rates (risk 1%)",
        md_table(tables["pass_vs_win_rate"].iloc[::5], {"win_rate": ".2f", "pass": pct,
                                                         "expected_days": ".1f", "expectancy_R": "+.2f"}),
        "![Pass vs win rate](pass_vs_win_rate.png)",
        "![Heatmap, payoff](heatmap_payoff.png)",
        "![Heatmap, risk](heatmap_risk.png)",
        "## 4. Kelly",
        md_table(tables["kelly_curves"].fillna(float("nan")),
                 {"case": "", "win_rate": ".3f", "kelly_fraction": "+.3f"}),
        md_table(tables["kelly_curves"].dropna(subset=["growth_full"]), {"case": "", "growth_full": ".4f",
                                                    "growth_share_0.25x": pct, "growth_share_0.5x": pct,
                                                    "growth_share_2x": pct}),
        "![Kelly growth](kelly_growth.png)",
        "### Drawdowns over 500 trades (20,000 simulated paths, record edge)",
        md_table(tables["kelly_drawdowns"], {"multiplier": ".2f", "fraction": ".3f", "growth": ".4f",
                                             "p_drawdown_20pct": pct, "p_drawdown_50pct": pct,
                                             "p_drawdown_80pct": pct}),
        "### Estimating the win rate from n trades, then betting a multiple of Kelly",
        md_table(tables["kelly_estimation_error"], {"n_trades": ".0f", "best_multiplier": ".2f",
                                                    "growth_share_at_best": pct,
                                                    "growth_share_full_kelly": pct,
                                                    "p_losing_growth_full_kelly": pct,
                                                    "p_over_twice_kelly_full": pct}),
        "![Estimation error](kelly_estimation_error.png)",
    ])
    (RESULTS / "RESULTS.md").write_text(report + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
